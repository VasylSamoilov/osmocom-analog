#define MCC_TABLE_SIZE \
	(sizeof(mcc_table) / sizeof(mcc_table[0]))

/* Look up country/area name for an E.212 MCC value.
 * Returns short name string, or "MCC:NNN" if not found. */
static inline const char *mcc_name(uint16_t mcc)
{
	unsigned int i;
	for (i = 0; i < MCC_TABLE_SIZE; i++) {
		if (mcc_table[i].code == mcc)
			return mcc_table[i].name;
	}
	return NULL;
}

/* Validate an E.212 MCC: must be 3 decimal digits (200-999).
 * MCCs 0xx, 1xx, 8xx are reserved per ITU. */
static inline int mcc_valid(uint16_t mcc)
{
	return (mcc >= 200 && mcc <= 999);
}

